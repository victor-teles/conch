#!/usr/bin/env bun
import type { ContrastEntry, Theme } from "@conch/rpc";

import {
  BUILTIN_THEMES,
  parseThemeColor,
  THEME_TOKENS,
  themeContrastReport,
  toHex,
} from "@conch/rpc";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(HERE, "..", "docs", "color-tokens.md");

const STATUS = { block: "BLOCK", ok: "PASS", warn: "FAIL" } as const;

const pairTable = (entries: readonly ContrastEntry[]): string =>
  [
    "| Foreground | Over | Ratio | Minimum | Status |",
    "| --- | --- | ---: | ---: | :---: |",
    ...entries.map(
      ({ level, pair, ratio }) =>
        `| \`--${pair.fg}\` | ${pair.over.map((layer) => `\`--${layer}\``).join(" → ")} | ${ratio.toFixed(2)} | ${pair.min.toFixed(1)} | ${STATUS[level]} |`
    ),
  ].join("\n");

const tokenTable = (theme: Theme): string =>
  [
    "| Token | Value | sRGB |",
    "| --- | --- | --- |",
    ...THEME_TOKENS.map(({ name }) => {
      const value = theme.tokens[name];
      const color = parseThemeColor(value);
      return `| \`--${name}\` | \`${value}\` | \`${color ? toHex(color) : "?"}\` |`;
    }),
  ].join("\n");

const section = (theme: Theme, entries: readonly ContrastEntry[]): string =>
  [
    `## ${theme.name} (\`${theme.id}\`, ${theme.appearance})`,
    "",
    pairTable(entries),
    "",
    "<details><summary>Tokens</summary>",
    "",
    tokenTable(theme),
    "",
    "</details>",
    "",
  ].join("\n");

const main = (): void => {
  const reports = BUILTIN_THEMES.map(
    (theme) => [theme, themeContrastReport(theme)] as const
  );

  writeFileSync(
    OUT_PATH,
    [
      "# Color Token WCAG AA Audit",
      "",
      "Generated by `apps/app/scripts/audit-contrast.ts` from the built-in",
      "themes in `packages/rpc/src/theme-builtins.ts`. Re-run with",
      "`bun run apps/app/scripts/audit-contrast.ts` after changing any token.",
      "",
      "Translucent layers are composited in gamma-encoded sRGB, as CSS does,",
      "from the bottom up over a reference wallpaper: dark `#1a1a1c`,",
      "light `#f0f0f1`. Minimums: text 4.5:1, UI marks and focus rings 3:1.",
      "The theme editor runs the same pairs on custom themes.",
      "",
      ...reports.map(([theme, entries]) => section(theme, entries)),
    ].join("\n")
  );

  const failures = reports.flatMap(([theme, entries]) =>
    entries
      .filter((entry) => entry.level !== "ok")
      .map(
        ({ pair, ratio }) =>
          `  ${theme.id} FAIL ${ratio.toFixed(2)} (need ${pair.min}): --${pair.fg} over ${pair.over.join(" → ")}`
      )
  );
  const pairs = reports.reduce((sum, [, entries]) => sum + entries.length, 0);
  console.log(
    `Audited ${pairs} pairs across ${reports.length} themes. ${failures.length} failing.\n${failures.join("\n")}`.trimEnd()
  );
  console.log(`Report written to ${OUT_PATH}`);
  if (failures.length > 0) {
    process.exit(1);
  }
};

main();
